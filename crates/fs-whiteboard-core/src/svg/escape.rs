//! XML escaping for text and attribute values.
//!
//! Pattern: Strategy (character rule) — `&`, `<`, `>`, `"` and `'` become entities; characters XML 1.0
//! does not allow at all are dropped, so the document stays well-formed whatever the text holds.

/// `s` as XML text or attribute value.
pub fn escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&apos;"),
            '\t' | '\n' | '\r' => out.push(c),
            c if (c as u32) < 0x20 || matches!(c as u32, 0xFFFE | 0xFFFF) => {}
            c => out.push(c),
        }
    }
    out
}
